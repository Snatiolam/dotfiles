-- Refer to https://wiki.hypr.land/Configuring/Basics/Variables/

local col_mauve       = "rgba(c6a0f6ee)"
local col_rosewater   = "rgba(f4dbd6ee)"
local col_baseAlpha00 = "rgba(00000000)"

hl.config({
    general = {
        gaps_in  = 5,
        gaps_out = 10,

        border_size = 2,

        col = {
            active_border   = { colors = {col_mauve, col_rosewater}, angle = 45 },
            inactive_border = col_baseAlpha00,
        },

        -- Resize tiled windows by dragging their borders and gaps.
        resize_on_border = true,
        extend_border_grab_area = 8,
        hover_icon_on_border = true,

        -- Please see https://wiki.hypr.land/Configuring/Advanced-and-Cool/Tearing/ before you turn this on
        allow_tearing = false,

        layout = "dwindle",
    },

    decoration = {
        rounding       = 10,
        rounding_power = 2,

        -- Change transparency of focused and unfocused windows
        active_opacity   = 1.0,
        inactive_opacity = 1.0,

        shadow = {
            enabled      = true,
            range        = 4,
            render_power = 3,
            color        = 0xee1a1a1a,
        },

        blur = {
            enabled   = true,
            size      = 3,
            passes    = 1,
            vibrancy  = 0.1696,
        },
    },

    animations = {
        enabled = true,
    },
})

-- Default curves and animations, see https://wiki.hypr.land/Configuring/Advanced-and-Cool/Animations/
hl.curve("easeOutQuint",   { type = "bezier", points = { {0.23, 1},    {0.32, 1}    } })
